-- SOLO PARA EL PROYECTO DE PRUEBA CONFIRMADO CON DATOS FICTICIOS.
-- Estas políticas hacen que cualquier visitante pueda leer y modificar estas tablas.

create table if not exists public.viviendas (
    id bigint generated by default as identity primary key,
    housing_id text not null,
    colonia text not null,
    address text not null,
    visit_date date,
    visit_time time
);
create table if not exists public.participantes (
    id bigint generated by default as identity primary key,
    vivienda_id bigint not null references public.viviendas (id) on delete cascade,
    rol text not null check (rol in ('PersonaA', 'PersonaB')),
    nombre text not null,
    status text not null default 'pending'
        check (status in ('pending', 'completed', 'rescheduled')),
    reschedule_reason text not null default ''
);
create table if not exists public.checklists (
    id bigint generated by default as identity primary key,
    participante_id bigint not null references public.participantes (id) on delete cascade,
    vital_signs boolean not null default false,
    hemoglobin boolean not null default false,
    glucose boolean not null default false,
    urine_sample boolean not null default false
);

alter table public.viviendas
    add column if not exists visit_date date,
    add column if not exists visit_time time;

grant usage on schema public to anon;
grant select, insert, update on public.viviendas, public.participantes, public.checklists to anon;
grant usage, select on sequence
    public.viviendas_id_seq,
    public.participantes_id_seq,
    public.checklists_id_seq
to anon;

create unique index if not exists viviendas_housing_id_unique
    on public.viviendas (housing_id);
create unique index if not exists participantes_vivienda_rol_unique
    on public.participantes (vivienda_id, rol);
create unique index if not exists checklists_participante_id_unique
    on public.checklists (participante_id);

alter table public.viviendas enable row level security;
alter table public.participantes enable row level security;
alter table public.checklists enable row level security;

drop policy if exists demo_anon_select on public.viviendas;
